/** 박스 없이 아이콘만 (날짜별 기록 카드 하단 등). height 기준으로 비율 유지 */
export function ActionIcon({ kind, active = true, height, color }: { kind: ActionKind; active?: boolean; height?: number; color?: string }) {
  const icon = ICONS[kind];
  const fill = active ? (color ?? ACTIVE_COLOR[kind]) : INACTIVE_COLOR;
  const opacity = active ? 1 : INACTIVE_OPACITY;
  const h = height ?? icon.h;
  const w = (icon.w / icon.h) * h;
  return (
    <Svg width={w} height={h} viewBox={icon.vb} fill="none">
      {icon.paths.map((d, i) => (
        <Path key={i} d={d} fill={fill} fillOpacity={opacity} />
      ))}
    </Svg>
  );
}

interface Props {
  kind: ActionKind;
  active: boolean;
  onPress?: () => void;
}

export default function ActionIconButton({ kind, active, onPress }: Props) {
  return (
    <TouchableOpacity
      style={styles.btn}
      activeOpacity={0.7}
      disabled={!active || !onPress}
      onPress={onPress}
      accessibilityRole="button"
      accessibilityLabel={ACTION_LABELS[kind]}
      accessibilityState={{ disabled: !active }}
    >
      <ActionIcon kind={kind} active={active} />
    </TouchableOpacity>
  );
}

